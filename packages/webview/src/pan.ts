/**
 * Drag-to-pan: holding the left (or middle) mouse button on the diagram and moving scrolls
 * the container. A press that doesn't move past a small threshold stays a normal click, so
 * clicking messages/participants still works; a press that pans suppresses the click that
 * follows. Elements with their own drag behaviour (participant heads, class boxes) opt out
 * via `isDraggable`.
 */
export interface PanOptions {
  /** True if a press on this target starts another drag (and must not pan). */
  isDraggable(target: EventTarget | null): boolean;
}

/**
 * Screen pixels a press may move and still count as a click. Real clicks (especially on
 * trackpads) wobble a few pixels; with a smaller value they turn into drags/pans and the
 * click (navigate) is swallowed.
 */
export const CLICK_SLOP = 6;

export function enablePan(scroll: HTMLElement, opts: PanOptions): () => void {
  const win = scroll.ownerDocument.defaultView!;
  let pan: { x: number; y: number; left: number; top: number; moved: boolean } | null = null;

  const onDown = (e: MouseEvent) => {
    if ((e.button !== 0 && e.button !== 1) || opts.isDraggable(e.target)) return;
    // Presses on the scrollbars keep their native behaviour.
    const r = scroll.getBoundingClientRect();
    if (scroll.clientWidth > 0 && (e.clientX - r.left >= scroll.clientWidth || e.clientY - r.top >= scroll.clientHeight)) return;
    pan = { x: e.clientX, y: e.clientY, left: scroll.scrollLeft, top: scroll.scrollTop, moved: false };
    if (e.button === 1) e.preventDefault(); // no autoscroll widget
  };

  const onMove = (e: MouseEvent) => {
    if (!pan) return;
    const dx = e.clientX - pan.x;
    const dy = e.clientY - pan.y;
    if (!pan.moved) {
      if (Math.hypot(dx, dy) < CLICK_SLOP) return;
      pan.moved = true;
      scroll.classList.add('panning');
      win.getSelection()?.removeAllRanges();
    }
    e.preventDefault();
    scroll.scrollLeft = pan.left - dx;
    scroll.scrollTop = pan.top - dy;
  };

  const onUp = () => {
    if (!pan) return;
    const moved = pan.moved;
    pan = null;
    scroll.classList.remove('panning');
    if (!moved) return;
    // Swallow the click generated by this mouseup so it doesn't navigate.
    const swallow = (ev: MouseEvent) => {
      ev.stopPropagation();
      ev.preventDefault();
    };
    scroll.addEventListener('click', swallow, { capture: true, once: true });
    setTimeout(() => scroll.removeEventListener('click', swallow, { capture: true }), 0);
  };

  scroll.addEventListener('mousedown', onDown);
  win.addEventListener('mousemove', onMove);
  win.addEventListener('mouseup', onUp);
  return () => {
    scroll.removeEventListener('mousedown', onDown);
    win.removeEventListener('mousemove', onMove);
    win.removeEventListener('mouseup', onUp);
  };
}
